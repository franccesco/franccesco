const cache = {};

// Convert a bitmap into SVG path data: one horizontal run per `M x y h n v1 h-n z`.
function trace(rows, mark) {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] !== mark) continue;
      let end = x;
      while (row[end + 1] === mark) end += 1;
      d += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
      x = end;
    }
  });
  return d;
}

function iconPaths(name) {
  if (!cache[name]) {
    const rows = (BITMAPS[name] || BITMAPS.file).trim().split('\n');
    cache[name] = [trace(rows, '#'), trace(rows, '@')];
  }
  return cache[name];
}

export { BITMAPS, iconPaths };
